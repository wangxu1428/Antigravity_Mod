const fs = require('fs');
const path = require('path');

const baseDir = __dirname;
const pluginsDir = path.dirname(baseDir);
const outputFile = path.join(pluginsDir, 'hakimi-i18n.js');

console.log('[Hakimi i18n Build] Bundling modular sources...');

// 1. Read locale dictionaries
const zhDir = path.join(baseDir, 'locales', 'zh-CN');
const exactDict = JSON.parse(fs.readFileSync(path.join(zhDir, 'dict-exact.json'), 'utf8'));
const prefixDict = JSON.parse(fs.readFileSync(path.join(zhDir, 'dict-prefix.json'), 'utf8'));
const regexDict = JSON.parse(fs.readFileSync(path.join(zhDir, 'dict-regex.json'), 'utf8'));
const coreDict = JSON.parse(fs.readFileSync(path.join(zhDir, 'dict-core.json'), 'utf8'));
const menuDict = JSON.parse(fs.readFileSync(path.join(zhDir, 'dict-menu.json'), 'utf8'));
const trayDict = JSON.parse(fs.readFileSync(path.join(zhDir, 'dict-tray.json'), 'utf8'));

// 2. Read custom templates
const customDir = path.join(baseDir, 'custom');
const overrides = JSON.parse(fs.readFileSync(path.join(customDir, 'overrides.json'), 'utf8'));
const exclusions = JSON.parse(fs.readFileSync(path.join(customDir, 'exclusions.json'), 'utf8'));
const glossary = JSON.parse(fs.readFileSync(path.join(customDir, 'glossary.json'), 'utf8'));

// 3. Read module sources
const sanitizerCode = fs.readFileSync(path.join(baseDir, 'core', 'sanitizer.js'), 'utf8');
const discoveryCode = fs.readFileSync(path.join(baseDir, 'core', 'discovery.js'), 'utf8');
const engineCode = fs.readFileSync(path.join(baseDir, 'core', 'engine.js'), 'utf8');
const domAdapterCode = fs.readFileSync(path.join(baseDir, 'adapters', 'dom-adapter.js'), 'utf8');
const configUiCode = fs.readFileSync(path.join(baseDir, 'ui', 'config-center.js'), 'utf8');

const officialData = {
    exact: exactDict,
    prefix: prefixDict,
    regex: regexDict,
    core: coreDict,
    menu: menuDict,
    tray: trayDict
};

const defaultCustom = {
    customOverrides: overrides.terms || {},
    exclusions: exclusions.terms || [],
    glossary: glossary.terms || {}
};

const bundleParts = [
`// =============================================================================
// Hakimi i18n v1.1 - Antigravity_Mod Deep Localization Plugin (Standalone Runtime)
// Generated by Hakimi i18n Build Pipeline
// =============================================================================
(function() {
    'use strict';
    console.log('[Hakimi i18n] Loading Hakimi i18n v1.1...');

    // Teardown previous instance if reloading
    if (typeof window.__hakimiI18nTeardown === 'function') {
        try {
            window.__hakimiI18nTeardown();
        } catch (e) {
            console.warn('[Hakimi i18n] Teardown error:', e);
        }
    }

    // --- Embedded Module: Sanitizer ---
`,
sanitizerCode,
`
    const Sanitizer = window.__HakimiSanitizer || {};

    // --- Embedded Module: Discovery ---
`,
discoveryCode,
`
    const Discovery = window.__HakimiDiscovery || {};

    // --- Embedded Module: Engine ---
`,
engineCode,
`
    const { TranslationEngine } = window.__HakimiEngine || {};

    // --- Embedded Module: DOM Adapter ---
`,
domAdapterCode,
`
    const { DOMAdapter } = window.__HakimiDOMAdapter || {};

    // --- Embedded Module: Config Center UI ---
`,
configUiCode,
`
    const { ConfigCenterUI } = window.__HakimiConfigUI || {};

    // --- Official Dictionary Data ---
    const OFFICIAL_DATA = `,
JSON.stringify(officialData),
`;
    const DEFAULT_CUSTOM = `,
JSON.stringify(defaultCustom),
`;

    // --- Plugin Lifecycle Controller ---
    let engine = null;
    let domAdapter = null;
    let configUI = null;

    function initHakimiI18n(hostConfig) {
        try {
            console.log('[Hakimi i18n] Initializing engine with host config...');
            
            if (typeof TranslationEngine !== 'function') {
                throw new Error('TranslationEngine constructor is not available!');
            }

            // 1. Initialize Engine
            engine = new TranslationEngine({ DiscoveryLib: Discovery, sanitizer: Sanitizer });
            engine.loadOfficialData(OFFICIAL_DATA);

            // 2. Merge config from host
            const savedI18n = (hostConfig && hostConfig.i18n) ? hostConfig.i18n : {};
            const mergedConfig = {
                enabled: savedI18n.enabled !== undefined ? savedI18n.enabled : true,
                language: savedI18n.language || 'zh-CN',
                preset: savedI18n.preset || 'full',
                scope: savedI18n.scope || {
                    menu: true, settings: true, agent: true, models: true,
                    requests: true, errors: true, native: true, plugins: true
                },
                customOverrides: { ...DEFAULT_CUSTOM.customOverrides, ...(savedI18n.customOverrides || {}) },
                exclusions: Array.from(new Set([...DEFAULT_CUSTOM.exclusions, ...(savedI18n.exclusions || [])])),
                glossary: { ...DEFAULT_CUSTOM.glossary, ...(savedI18n.glossary || {}) }
            };

            engine.updateConfig(mergedConfig);
            console.log('[Hakimi i18n] config.enabled=' + engine.config.enabled + ' language=' + engine.config.language);

            // 3. Initialize DOM Adapter
            domAdapter = new DOMAdapter(engine, Sanitizer);

            // 4. Initialize Configuration Center UI
            const onSaveConfig = async (updatedCfg) => {
                console.log('[Hakimi i18n] Saving updated configuration...');
                if (typeof window.__hakimiCustomSaveHandler === 'function') {
                    const customOk = await window.__hakimiCustomSaveHandler(updatedCfg);
                    if (customOk === false) {
                        throw new Error('自定义保存处理器返回失败');
                    }
                    return customOk;
                }
                if (window.hakimiHost && typeof window.hakimiHost.readConfig === 'function' && typeof window.hakimiHost.saveConfig === 'function') {
                    const fullCfg = await window.hakimiHost.readConfig();
                    const next = fullCfg || {};
                    next.i18n = updatedCfg;
                    const saved = await window.hakimiHost.saveConfig(next);
                    if (saved === false) {
                        throw new Error('写入 plugins/config.json 失败');
                    }
                    return saved;
                }
                if (window.localStorage) {
                    window.localStorage.setItem('hakimi_i18n_config', JSON.stringify(updatedCfg));
                }
                return true;
            };

            configUI = new ConfigCenterUI(engine, domAdapter, onSaveConfig);
            configUI.init();

            // 5. Start translation if enabled
            if (engine.config.enabled && engine.config.language === 'zh-CN') {
                domAdapter.start();
            } else {
                console.log('[Hakimi i18n] Translation inactive (config.enabled=' + engine.config.enabled + ', language=' + engine.config.language + '); skipping domAdapter.start().');
            }

            // 6. Register teardown for clean hot-reload (Ctrl+R / F5)
            window.__hakimiI18nTeardown = () => {
                const enabledNow = engine && engine.config ? engine.config.enabled : undefined;
                console.log('[Hakimi i18n] Tearing down Hakimi i18n instance... config.enabled=' + enabledNow);
                if (domAdapter) {
                    try {
                        if (typeof domAdapter.restoreEnglish === 'function') {
                            domAdapter.restoreEnglish();
                        }
                    } catch (e) {
                        console.warn('[Hakimi i18n] restoreEnglish error during teardown:', e);
                    }
                    if (typeof domAdapter.stop === 'function') {
                        domAdapter.stop();
                    }
                }
                if (configUI) {
                    configUI.destroy();
                }
                window.__hakimiI18nTeardown = null;
            };

            const runLiveAudit = () => {
                const body = document.body;
                const uiCandidates = engine.getUntranslatedList('default');
                const allCandidates = engine.getUntranslatedList('all');
                const report = {
                    version: '1.1.0',
                    timestamp: new Date().toISOString(),
                    enabled: !!engine.config.enabled,
                    language: engine.config.language,
                    translatedTextCount: 0,
                    inputControls: [],
                    projectSelectors: [],
                    untranslatedDefaultCount: uiCandidates.length,
                    untranslatedAllCount: allCandidates.length,
                    uiCandidates: uiCandidates.slice(0, 50).map(item => ({
                        text: item.text,
                        category: item.category,
                        count: item.count,
                        sourceHint: item.sourceHint
                    }))
                };
                if (!body || typeof document.createTreeWalker !== 'function') return report;

                const walker = document.createTreeWalker(body, NodeFilter.SHOW_TEXT, null);
                let tn;
                while ((tn = walker.nextNode())) {
                    if (tn.__agyOrigText !== undefined) {
                        report.translatedTextCount++;
                    }
                    const txt = (tn.nodeValue || '').trim();
                    const orig = (tn.__agyOrigText || txt).trim();
                    if (/^(No Project|未选择项目)$/i.test(orig) || /^(No Project|未选择项目)$/i.test(txt)) {
                        const parent = tn.parentElement;
                        report.projectSelectors.push({
                            orig,
                            current: txt,
                            translated: txt !== orig,
                            immune: parent && Sanitizer ? Sanitizer.isElementImmune(parent) : false
                        });
                    }
                }

                if (typeof body.querySelectorAll === 'function') {
                    const controls = body.querySelectorAll('input[placeholder], textarea[placeholder], [contenteditable="true"], [data-placeholder]');
                    for (let i = 0; i < controls.length; i++) {
                        const el = controls[i];
                        if (Sanitizer && Sanitizer.isPluginOwnElement && Sanitizer.isPluginOwnElement(el)) continue;
                        const ph = el.getAttribute('placeholder') || el.getAttribute('data-placeholder') || '';
                        const origPh = (el.__agyOrigAttrs && (el.__agyOrigAttrs.placeholder || el.__agyOrigAttrs['data-placeholder'])) || '';
                        report.inputControls.push({
                            tag: el.tagName,
                            origPlaceholder: origPh || ph,
                            currentPlaceholder: ph,
                            translated: !!origPh && ph !== origPh,
                            immune: Sanitizer ? Sanitizer.isElementImmune(el) : false
                        });
                    }
                }
                return report;
            };

            // Expose global debug API
            window.__HAKIMI_I18N__ = {
                engine,
                domAdapter,
                configUI,
                version: '1.1.0',
                translate: (t) => engine.translate(t),
                restoreEnglish: () => domAdapter.restoreEnglish(),
                toggleUI: () => configUI.toggle(),
                runLiveAudit
            };

            console.log('[Hakimi i18n] Plugin initialized successfully! Ready for duty 🐾');
        } catch (err) {
            console.error('[Hakimi i18n CRITICAL INIT ERROR]:', err);
        }
    }

    // Register into HakimiPluginHost
    if (window.HakimiPluginHost && typeof window.HakimiPluginHost.register === 'function') {
        window.HakimiPluginHost.register('hakimi-i18n', {
            name: 'Hakimi i18n Deep Localization Engine',
            version: '1.1.0',
            init: function(hostConfig) {
                initHakimiI18n(hostConfig);
            }
        });
    } else {
        // Fallback standalone initialization
        if (window.hakimiHost && typeof window.hakimiHost.readConfig === 'function') {
            window.hakimiHost.readConfig().then(initHakimiI18n).catch(() => initHakimiI18n({}));
        } else {
            initHakimiI18n({});
        }
    }
})();
`
];

fs.writeFileSync(outputFile, bundleParts.join(''), 'utf8');
const stat = fs.statSync(outputFile);
console.log(`[Hakimi i18n Build] Successfully generated: ${outputFile}`);
console.log(`[Hakimi i18n Build] Bundle size: ${stat.size} bytes (${(stat.size / (1024*1024)).toFixed(2)} MB)`);
